// Inject bundled PalBuilder context into a pal workspace WITHOUT clobbering user content.
//   - .claude/skills/<name>/SKILL.md  (copied from bundle; palsync-owned, progressive-disclosure depth)
//   - CLAUDE.palsync.md  = the SINGLE palsync-owned doc: the static coding contract (bundled CLAUDE.md)
//                          + the templated sync/creation/dataset rules, under one version stamp.
//                          Regenerated wholesale each setup, so the rules live in ONE file and can't
//                          drift between two.
//   - CLAUDE.md          = the user's file, with a tiny managed block that `@CLAUDE.palsync.md`-imports
//                          the owned doc. The import is on its own line and un-backticked — Claude
//                          Code's import parser skips code spans, so a backticked @ref would NOT load.
// Re-running setup rewrites the owned doc + the managed block + prunes retired skills; a teammate's own
// CLAUDE.md notes (outside the markers) survive. `contextStatus()` compares the doc's stamp to the
// installed build so `palsync status` can flag a workspace that needs a relaunch to refresh.
const fs = require("fs/promises");
const path = require("path");

const BUNDLE_DIR = path.join(__dirname, "..", "..", "bundled-context");
const VERSION = require("../../package.json").version;

// Stamp the owned doc with the palsync version that generated it, so `palsync status` can flag a
// workspace whose context predates the installed build (relaunch re-injects and refreshes it).
const STAMP_RE = /<!--\s*palsync-context\s+v([0-9][^\s]*)/;
function stampComment() {
    return "<!-- palsync-context v" + VERSION + " — regenerated by palsync setup; do not edit by hand -->";
}

// Skill dir names palsync has shipped but later renamed/removed. Pruned from a workspace if present
// so a re-inject drops them (e.g. design-core → design-system-init + design-build). User-added skills
// (names palsync never owned) are never touched.
const RETIRED_SKILLS = ["design-core", "palbuilder-design", "design"];

// Every skill in the bundle loads every session — the bundle dir IS the inventory, discovered at
// inject time (see bundledSkills), so a newly-added skill ships automatically with no hand-kept
// list to drift out of sync. Skills cost no context until the agent opens one (only their
// name+description are read at startup); each skill's references/* ride along so a SKILL.md that
// links them always has them in the workspace.
const BEGIN = "<!-- >>> palsync managed block — do not edit; regenerated by palsync setup >>> -->";
const END = "<!-- <<< palsync managed block <<< -->";

