// The single palsync-owned doc: the static PalBuilder coding contract (bundled CLAUDE.md) + the
// templated sync-etiquette/creation/dataset rules, under one version stamp. Written byte-for-byte to
// CLAUDE.palsync.md (and inlined into AGENTS.md for codex/pi) — regenerated wholesale every setup, so
// the rules live in ONE place and cannot drift between two files.
async function buildPalsyncDoc(palName, opts) {
    const contract = (await fs.readFile(path.join(BUNDLE_DIR, "CLAUDE.md"), "utf8")).trim();
    return [stampComment(), "", contract, "", "---", "", syncSection(palName, opts)].join("\n") + "\n";
}

// CLAUDE.md managed block (Claude): a REAL `@import` of the owned doc — must be on its own line and
// NOT inside backticks, or Claude Code's import parser skips it (it ignores code spans). Tiny + stable:
// only the stamp changes between versions, so re-inject never churns the user's surrounding prose.
function importBlock() {
    return [BEGIN,
        stampComment(),
        "PalBuilder rules for this pal are maintained by palsync in `CLAUDE.palsync.md` and loaded via",
        "the import below. It is regenerated on each `palsync` launch — edit it only through palsync.",
        "",
        "@CLAUDE.palsync.md",
        END].join("\n");
}

// AGENTS.md managed block (codex/pi): the FULL doc inlined. Those agents read AGENTS.md natively but
// their `@import` support is unreliable, so the rules go in directly rather than via a reference.
function agentsBlock(doc) {
    return BEGIN + "\n" + doc.trimEnd() + "\n" + END;
}

// Insert or replace the managed block, preserving all user content outside the markers.
function mergeManaged(existing, block) {
    if (existing == null) {
        return { content: block + "\n", mode: "created" };
    }
    const b = existing.indexOf(BEGIN);
    const e = existing.indexOf(END);
    if (b !== -1 && e !== -1 && e > b) {
        // Replace existing managed region in place; keep everything else verbatim.
        const before = existing.slice(0, b);
        const after = existing.slice(e + END.length);
        return { content: before + block + after, mode: "refreshed" };
    }
    // Append the block, preserving the user's existing content above it.
    const sep = existing.endsWith("\n") ? "\n" : "\n\n";
    return { content: existing + sep + block + "\n", mode: "appended" };
}

async function copyFile(src, dest) {
    await fs.mkdir(path.dirname(dest), { recursive: true });
    await fs.copyFile(src, dest);
}

async function readIfExists(p) {
    try { return await fs.readFile(p, "utf8"); }
    catch (e) { if (e.code === "ENOENT") return null; throw e; }
}

// Discover every skill shipped in the bundle: each subdir of bundled-context/skills/ that has a
// SKILL.md, normalized to { name, assets } where assets are the files under its references/
// (auto-shipped). The bundle dir is the single source of truth — no list to keep in sync with disk.
async function bundledSkills() {
    const skillsRoot = path.join(BUNDLE_DIR, "skills");
    let entries;
    try { entries = await fs.readdir(skillsRoot, { withFileTypes: true }); }
    catch (e) { if (e.code === "ENOENT") return []; throw e; }
    const out = [];
    for (const ent of entries) {
        if (!ent.isDirectory()) continue;
        const dir = path.join(skillsRoot, ent.name);
        try { await fs.access(path.join(dir, "SKILL.md")); }
        catch (e) { continue; } // a dir without SKILL.md is not a skill — skip it
        let assets = [];
        try {
            const refs = await fs.readdir(path.join(dir, "references"), { withFileTypes: true });
            assets = refs.filter(r => r.isFile()).map(r => path.join("references", r.name));
        } catch (e) { /* no references/ — SKILL.md-only skill */ }
        out.push({ name: ent.name, assets });
    }
    return out;
}

// Copy a skill set's SKILL.md (+ companion assets) into <rootDir>/skills/<name>/.
// rootDir is the agent's skills root: ".claude" (Claude) or ".agents" (Codex open standard).
async function copySkillSet(workspaceDir, rootDir, skills) {
    for (const s of skills) {
        await copyFile(path.join(BUNDLE_DIR, "skills", s.name, "SKILL.md"),
                       path.join(workspaceDir, rootDir, "skills", s.name, "SKILL.md"));
        for (const asset of (s.assets || [])) {
            await copyFile(path.join(BUNDLE_DIR, "skills", s.name, asset),
                           path.join(workspaceDir, rootDir, "skills", s.name, asset));
        }
    }
}

// Every skill name palsync owns (current + retired). Used by pruneSkills to know which dirs are safe
// to remove — anything outside this set is a user-added skill and is left alone.
async function ownedSkillNames() {
    const names = (await bundledSkills()).map(s => s.name);
    return new Set([...names, ...RETIRED_SKILLS]);
}

// Remove palsync-owned skill dirs that are NOT in the effective set for this session (a skill that was
// dropped from always-on, renamed, or retired). copySkillSet only adds; without this the set only grows
// and stale skills linger forever. Returns the names removed.
async function pruneSkills(workspaceDir, rootDir, keepNames) {
    const skillsDir = path.join(workspaceDir, rootDir, "skills");
    let entries;
    try { entries = await fs.readdir(skillsDir, { withFileTypes: true }); }
    catch (e) { if (e.code === "ENOENT") return []; throw e; }
    const keep = new Set(keepNames);
    const owned = await ownedSkillNames();
    const removed = [];
    for (const ent of entries) {
        if (!ent.isDirectory()) continue;
        if (owned.has(ent.name) && !keep.has(ent.name)) {
            await fs.rm(path.join(skillsDir, ent.name), { recursive: true, force: true });
            removed.push(ent.name);
        }
    }
    return removed;
}

// Remove a workspace's managed block from a file, preserving any user content outside the markers.
// Deletes the file outright if nothing but whitespace remains. No-op if the file or block is absent.
async function stripManaged(filePath) {
    const existing = await readIfExists(filePath);
    if (existing == null) return false;
    const b = existing.indexOf(BEGIN), e = existing.indexOf(END);
    if (b === -1 || e === -1 || e <= b) return false;
    const rest = existing.slice(0, b) + existing.slice(e + END.length);
    if (rest.trim() === "") { await fs.rm(filePath, { force: true }); return true; }
    await fs.writeFile(filePath, rest, "utf8");
    return true;
}

// A workspace carries files for ONE agent — the one it was last launched with. When the selected agent
// isn't Claude, remove the Claude-owned artifacts (and vice-versa) so a Pi/Codex pal isn't littered with
// dead CLAUDE.* files and duplicate .claude/skills. Only palsync-owned content is touched; user notes in
// CLAUDE.md/AGENTS.md and user-authored skills survive.
// Remove a dir only if it is now empty (rmdir fails with ENOTEMPTY otherwise) — so an emptied
// .claude/skills (and .claude itself) goes, but a dir still holding user settings is left alone.
async function rmDirIfEmpty(dir) {
    try { await fs.rmdir(dir); return true; } catch (e) { return false; }
}
async function pruneAgentRoot(workspaceDir, rootDir) {
    const removed = await pruneSkills(workspaceDir, rootDir, []);
    await rmDirIfEmpty(path.join(workspaceDir, rootDir, "skills"));
    await rmDirIfEmpty(path.join(workspaceDir, rootDir));
    return removed;
}
async function cleanClaudeArtifacts(workspaceDir) {
    await fs.rm(path.join(workspaceDir, "CLAUDE.palsync.md"), { force: true });
    await stripManaged(path.join(workspaceDir, "CLAUDE.md"));
    return pruneAgentRoot(workspaceDir, ".claude");
}
async function cleanAgentsArtifacts(workspaceDir) {
    await stripManaged(path.join(workspaceDir, "AGENTS.md"));
    return pruneAgentRoot(workspaceDir, ".agents");
}

// Read the version stamp off whichever owned doc this workspace carries (CLAUDE.palsync.md for Claude,
// AGENTS.md for Codex/Pi) and compare to the installed build. `palsync status` uses this to flag a
// workspace that predates the current build (relaunch refreshes it).
async function contextStatus(workspaceDir) {
    for (const file of ["CLAUDE.palsync.md", "AGENTS.md"]) {
        const txt = await readIfExists(path.join(workspaceDir, file));
        if (txt == null) continue;
        const m = txt.match(STAMP_RE);
        const version = m ? m[1] : null;
        return { present: true, file, version, current: VERSION, stale: version !== VERSION };
    }
    return { present: false, file: null, version: null, current: VERSION, stale: true };
}

